import { ArrowLeft, FileText, ShieldCheck } from 'lucide-react';

type LegalPage = 'privacy' | 'terms';

interface PublicLegalPageProps {
  page: LegalPage;
}

const pageContent = {
  privacy: {
    icon: ShieldCheck,
    eyebrow: 'Privacy policy',
    title: 'DreamBank AI Privacy Policy',
    intro: 'DreamBank AI is a hackathon prototype.',
    paragraphs: [
      'User financial information is used only to:',
      'We do not sell personal information.',
      'This application uses PayPal for authentication and payment-related features.',
    ],
    bullets: [
      'Provide AI-powered savings recommendations',
      'Analyze savings goals',
      'Generate affordability forecasts',
      'Improve user financial insights',
    ],
  },
  terms: {
    icon: FileText,
    eyebrow: 'Terms of use',
    title: 'DreamBank AI Terms of Use',
    intro: 'DreamBank AI is a prototype created for the PayPal AI Hackathon.',
    paragraphs: [
      'Financial recommendations generated by AI are estimates and should not be considered professional financial advice.',
      'Users are responsible for their own financial decisions.',
    ],
    bullets: [],
  },
} satisfies Record<LegalPage, {
  icon: typeof ShieldCheck;
  eyebrow: string;
  title: string;
  intro: string;
  paragraphs: string[];
  bullets: string[];
}>;

export function PublicLegalPage({ page }: PublicLegalPageProps) {
  const content = pageContent[page];
  const Icon = content.icon;

  return (
    <main className="min-h-screen bg-slate-50 px-4 py-8 text-slate-900 sm:px-6 sm:py-16">
      <article className="mx-auto max-w-3xl overflow-hidden rounded-3xl border border-slate-200 bg-white shadow-xl shadow-slate-900/5">
        <header className="bg-slate-900 px-6 py-8 text-white sm:px-10 sm:py-10">
          <a href="/" className="inline-flex items-center gap-2 text-sm font-semibold text-blue-200 transition hover:text-white">
            <ArrowLeft className="h-4 w-4" />
            Back to DreamBank AI
          </a>
          <div className="mt-10 flex items-start gap-4">
            <span className="flex h-12 w-12 shrink-0 items-center justify-center rounded-2xl bg-blue-600 text-white">
              <Icon className="h-6 w-6" />
            </span>
            <div>
              <p className="text-xs font-bold uppercase tracking-[0.18em] text-blue-200">{content.eyebrow}</p>
              <h1 className="mt-3 text-3xl font-bold tracking-tight sm:text-4xl">{content.title}</h1>
            </div>
          </div>
        </header>

        <div className="space-y-7 px-6 py-8 text-base leading-7 text-slate-700 sm:px-10 sm:py-10">
          <p>{content.intro}</p>
          {content.paragraphs.map((paragraph) => (
            <p key={paragraph}>{paragraph}</p>
          ))}
          {content.bullets.length > 0 && (
            <ul className="list-disc space-y-2 pl-6">
              {content.bullets.map((bullet) => <li key={bullet}>{bullet}</li>)}
            </ul>
          )}
        </div>

        <footer className="border-t border-slate-100 px-6 py-5 text-sm text-slate-500 sm:px-10">
          DreamBank AI · Hackathon prototype
        </footer>
      </article>
    </main>
  );
}
